export function getGrammarPool(difficulty: Difficulty): GrammarTierPool {
  if (difficulty === "easy") return EASY_POOL;
  if (difficulty === "medium") {
    return {
      sgNouns: [...EASY_POOL.sgNouns, ...MEDIUM_ADDITIONS.sgNouns],
      plOnlyNouns: [...EASY_POOL.plOnlyNouns, ...MEDIUM_ADDITIONS.plOnlyNouns],
      transVerbs: [...EASY_POOL.transVerbs, ...MEDIUM_ADDITIONS.transVerbs],
      intransVerbs: [...EASY_POOL.intransVerbs, ...MEDIUM_ADDITIONS.intransVerbs],
      adjs: [...EASY_POOL.adjs, ...MEDIUM_ADDITIONS.adjs],
      advs: [...EASY_POOL.advs, ...MEDIUM_ADDITIONS.advs],
      prepObjects: [...EASY_POOL.prepObjects, ...MEDIUM_ADDITIONS.prepObjects],
    };
  }
  return {
    sgNouns: [...EASY_POOL.sgNouns, ...MEDIUM_ADDITIONS.sgNouns, ...HARD_ADDITIONS.sgNouns],
    plOnlyNouns: [
      ...EASY_POOL.plOnlyNouns,
      ...MEDIUM_ADDITIONS.plOnlyNouns,
      ...HARD_ADDITIONS.plOnlyNouns,
    ],
    transVerbs: [
      ...EASY_POOL.transVerbs,
      ...MEDIUM_ADDITIONS.transVerbs,
      ...HARD_ADDITIONS.transVerbs,
    ],
    intransVerbs: [
      ...EASY_POOL.intransVerbs,
      ...MEDIUM_ADDITIONS.intransVerbs,
      ...HARD_ADDITIONS.intransVerbs,
    ],
    adjs: [...EASY_POOL.adjs, ...MEDIUM_ADDITIONS.adjs, ...HARD_ADDITIONS.adjs],
    advs: [...EASY_POOL.advs, ...MEDIUM_ADDITIONS.advs, ...HARD_ADDITIONS.advs],
    prepObjects: [
      ...EASY_POOL.prepObjects,
      ...MEDIUM_ADDITIONS.prepObjects,
      ...HARD_ADDITIONS.prepObjects,
    ],
  };
}
